export function dashTranslator(locale: Locale) {
  return (key: DashKey, vars?: Record<string, string | number>) => {
    let s: string = dashMessages[locale][key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

