export const fieldMessages: Record<Locale, Record<FieldKey, string>> = { en: fieldEn, bn: fieldBn };

export function fieldTranslator(locale: Locale) {
  return (key: FieldKey, vars?: Record<string, string | number>) => {
    let s: string = fieldMessages[locale][key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

